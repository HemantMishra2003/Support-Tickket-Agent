from dotenv import load_dotenv
from langchain_openai import OpenAIEmbeddings, ChatOpenAI
from langchain_community.vectorstores import FAISS

from llm_classifier import classify_ticket_details
from risk_detector import detect_student_risk


# ==========================================================
# 1. LOAD ENVIRONMENT VARIABLES
# ==========================================================

load_dotenv()


# ==========================================================
# 2. INITIALIZE MODELS
# ==========================================================

embeddings = OpenAIEmbeddings(
    model="text-embedding-3-small"
)

llm = ChatOpenAI(
    model="gpt-4.1-mini",
    temperature=0
)


# ==========================================================
# 3. LOAD FAISS KNOWLEDGE BASE
# ==========================================================

vector_store = FAISS.load_local(
    "faiss_index",
    embeddings,
    allow_dangerous_deserialization=True
)


# ==========================================================
# 4. HUMAN ESCALATION RULES
# ==========================================================

def should_escalate(ticket, classification, retrieved_docs):

    ticket_lower = ticket.lower()

    categories = classification["categories"]
    primary_category = classification["primary_category"]

    # Rule 1: Unclear complaint or explicit human review category
    if primary_category == "human_review":
        return True, "The complaint requires human review."

    # Rule 2: Classifier recommends human review
    if classification["needs_human_review"]:
        return True, "The classifier recommends human verification."

    # Rule 3: Payment or transaction verification
    payment_verification_phrases = [
        "money deducted",
        "payment deducted",
        "deducted but",
        "payment failed",
        "paid but",
        "charged but",
        "charged twice",
        "deducted twice",
        "double payment",
        "not activated",
        "batch not activated",
        "payment pending",
        "payment successful but",
        "verify my payment",
        "check my payment",
        "transaction reference"
    ]

    if any(
        phrase in ticket_lower
        for phrase in payment_verification_phrases
    ):
        return True, "Payment or transaction status needs verification."

    # Rule 4: Actual course or batch access problems
    if "batch_access" in categories:

        batch_verification_phrases = [
            "batch is missing",
            "batch missing",
            "batch not activated",
            "batch is not activated",
            "course is missing",
            "course missing",
            "cannot access my course",
            "can't access my course",
            "cannot access my batch",
            "can't access my batch",
            "cannot find my batch",
            "can't find my batch",
            "batch not visible",
            "batch is not visible",
            "purchased batch is missing"
        ]

        if any(
            phrase in ticket_lower
            for phrase in batch_verification_phrases
        ):
            return True, "Course or batch access may require verification."

    # Rule 5: Serious account or security issues
    security_phrases = [
        "account hacked",
        "account compromised",
        "unauthorized access",
        "someone accessed my account",
        "account stolen",
        "fraudulent transaction"
    ]

    if any(
        phrase in ticket_lower
        for phrase in security_phrases
    ):
        return True, "Account security requires human review."

    # Rule 6: Explicit request for human support
    human_support_phrases = [
        "talk to a human",
        "speak to a human",
        "talk to an agent",
        "speak to an agent",
        "human support",
        "contact a representative",
        "talk to customer support",
        "speak to customer support"
    ]

    if any(
        phrase in ticket_lower
        for phrase in human_support_phrases
    ):
        return True, "The student explicitly requested human support."

    # Rule 7: Missing documents
    # Academic doubts can still be answered using general knowledge.
    # Other categories require relevant knowledge-base information.
    if not retrieved_docs and "academic_doubt" not in categories:
        return True, "No knowledge-base documents were retrieved."

    # Rule 8: General refund policy questions can receive an auto-reply.
    # Actual account-specific refund verification is handled separately.

    # Rule 9: Academic doubts do not automatically require human review.
    # General educational explanations can be generated by the LLM.

    return False, "No predefined escalation rule was triggered."


# ==========================================================
# 5. PROCESS STUDENT TICKET
# ==========================================================

def process_ticket(ticket, conversation_history=None, attempt_number=1):

    # A. Classify the ticket
    classification = classify_ticket_details(ticket)

    categories = classification["categories"]
    primary_category = classification["primary_category"]

    # B. Assess student sentiment, risk, and priority
    risk_assessment = detect_student_risk(ticket)

    # C. Retrieve relevant knowledge-base documents
    retrieved_docs = vector_store.similarity_search(
        ticket,
        k=3
    )

    # D. Prepare retrieved context with source filenames
    context_parts = []

    for index, doc in enumerate(retrieved_docs, start=1):

        source = doc.metadata.get("source", "Unknown")

        context_parts.append(
            f"""
Document {index}
Source filename: {source}

Content:
{doc.page_content}
"""
        )

    context = "\n\n".join(context_parts)

    # E. Apply escalation rules
    escalate, reason = should_escalate(
        ticket,
        classification,
        retrieved_docs
    )

    # F. Apply risk-based escalation
    if risk_assessment["needs_human_review"]:

        escalate = True

        reason = (
            "Human review required based on student risk assessment: "
            + risk_assessment["reason"]
        )

    # G. Select instructions based on ticket category
    if "academic_doubt" in categories:

        response_instructions = """
You are a helpful academic tutor for students.

ACADEMIC SUPPORT RULES:

1. Answer the student's academic question using your general
   educational knowledge, even if the answer is not present
   in the retrieved knowledge-base documents.

2. Explain concepts in simple, student-friendly language.

3. Explain step by step when appropriate.

4. Use formulas, examples, and small calculations when useful.

5. For numerical problems, show the important calculation steps.

6. If the question is ambiguous, ask a relevant clarifying question.

7. Do not pretend that a general explanation comes from official
   PW notes or an official PW teacher.

8. Do not invent PW-specific course details, policies, or materials.

9. If the question is beyond your ability to answer reliably,
   acknowledge the limitation and recommend academic support.

10. End by asking whether the student understood the explanation
    or needs another example.

11. Keep the answer focused on the student's actual doubt.
"""

    else:

        response_instructions = """
You are an AI student support assistant.

NON-ACADEMIC SUPPORT RULES:

1. Use only facts supported by the retrieved knowledge-base documents.

2. Do not invent company policies, fees, discounts, contact details,
   refund rules, or troubleshooting procedures.

3. Never promise a refund.

4. Do not claim a payment succeeded or failed unless the available
   information verifies it.

5. For account-specific payment or enrollment verification,
   explain that human support needs to investigate.

6. If the documents do not contain sufficient information,
   acknowledge this limitation.

7. Do not claim that the issue has been resolved.

8. Give concise and helpful next steps only when supported
   by the retrieved information.
"""

    # H. Build the response prompt
    prompt = f"""
{response_instructions}

GENERAL RULES:

1. Be polite, professional, and empathetic.
2. Use readable paragraphs and proper punctuation.
3. Address every relevant issue in a multi-issue complaint.
4. Do not reveal internal classification rules or risk scores.
5. Do not claim that a ticket has been created, submitted,
   forwarded, or escalated unless an actual system action confirms it.
6. Clearly distinguish recommended human review from actual escalation.
7. Return only the reply intended for the student.

STUDENT TICKET:
{ticket}

DETECTED CATEGORIES:
{categories}

PRIMARY CATEGORY:
{primary_category}

STUDENT SENTIMENT:
{risk_assessment["sentiment"]}

STUDENT RISK LEVEL:
{risk_assessment["risk_level"]}

PRIORITY:
{risk_assessment["priority"]}

HUMAN REVIEW RECOMMENDED:
{escalate}

REVIEW REASON:
{reason}

CONVERSATION HISTORY:
{conversation_history if conversation_history else "This is the first response."}

CURRENT SUPPORT ATTEMPT:
{attempt_number} of 3

FOLLOW-UP BEHAVIOUR:
- If this is a follow-up, use the conversation history and do not repeat the same answer or troubleshooting step.
- For academic doubts, explain the concept differently or use a new example if the student did not understand.
- For technical problems, offer one different, safe troubleshooting step at a time, supported by the knowledge base.
- For fee, refund, payment, or batch-access problems, do not claim account verification or promise a resolution. If the matter needs account-specific investigation, recommend human review.
- Do not say the student is satisfied or the issue is resolved unless the student confirms it.
- Keep the reply directed to the student.

RETRIEVED KNOWLEDGE-BASE DOCUMENTS:
{context if context else "No documents were retrieved."}
"""

    # I. Generate the draft reply
    response = llm.invoke(prompt)

    # J. Determine recommended action
    if escalate:
        action = "HUMAN_REVIEW"
    else:
        action = "AUTO_REPLY_CANDIDATE"

    # K. Collect source filenames
    sources = sorted({
        doc.metadata.get("source", "Unknown")
        for doc in retrieved_docs
    })

    # L. Return the complete result
    return {
        "ticket": ticket,
        "categories": categories,
        "category": primary_category,

        "sentiment": risk_assessment["sentiment"],
        "risk_level": risk_assessment["risk_level"],
        "priority": risk_assessment["priority"],

        "classifier_needs_human_review":
            classification["needs_human_review"],

        "risk_needs_human_review":
            risk_assessment["needs_human_review"],

        "needs_human_review": escalate,
        "action": action,
        "reason": reason,

        "draft_reply": response.content,
        "sources": sources
    }


# ==========================================================
# 6. RUN THE AGENT
# ==========================================================

def run_interactive_conversation():
    """
    Runs a simple CLI satisfaction loop for all ticket categories.
    Conversation history is kept only in memory for this run.
    This does not actually send a ticket to a human-support system.
    """
    print("=" * 60)
    print("AI SUPPORT TICKET TRIAGE AGENT")
    print("=" * 60)

    ticket = input("\\nEnter student query: ").strip()
    if not ticket:
        print("Please enter a student query.")
        return

    conversation_history = []
    max_attempts = 3

    for attempt in range(1, max_attempts + 1):
        current_query = ticket if attempt == 1 else input(
            "\\nTell me what is still not solved (or type 'human support'): "
        ).strip()

        if not current_query:
            print("No follow-up provided. Ending the conversation.")
            return

        if any(phrase in current_query.lower() for phrase in [
            "human support", "talk to a human", "speak to an agent",
            "talk to an agent", "customer support"
        ]):
            print("\\nHuman review is recommended because the student requested human support.")
            print("No ticket has been sent automatically by this prototype.")
            return

        try:
            ticket_for_processing = (
                ticket if attempt == 1
                else f"Original student issue: {ticket}\\nStudent follow-up: {current_query}"
            )
            result = process_ticket(
                ticket_for_processing,
                conversation_history=conversation_history,
                attempt_number=attempt
            )

            print("\\n" + "=" * 60)
            print("TICKET TRIAGE RESULT")
            print("=" * 60)
            print("Categories:", result["categories"])
            print("Primary category:", result["category"])
            print("Sentiment:", result["sentiment"])
            print("Risk level:", result["risk_level"])
            print("Priority:", result["priority"])
            print("Human review recommended:", result["needs_human_review"])
            print("Action:", result["action"])
            print("Reason:", result["reason"])

            print("\\nDRAFT REPLY TO STUDENT")
            print("-" * 60)
            print(result["draft_reply"])

            print("\\nRETRIEVED SOURCES")
            if result["sources"]:
                for source in result["sources"]:
                    print("-", source)
            else:
                print("No sources found.")

            conversation_history.append({
                "student": current_query,
                "assistant": result["draft_reply"]
            })

            if result["needs_human_review"]:
                print("\\nNext step: human review is recommended.")
                print("This prototype does not actually forward or create a support ticket.")
                return

            satisfaction = input(
                "\\nIs the student satisfied with this response? (yes/no): "
            ).strip().lower()

            if satisfaction in {"yes", "y", "satisfied"}:
                print("\\nStatus: Student confirmed satisfaction. Mark as resolved in this demo.")
                return

            if satisfaction not in {"no", "n", "not satisfied"}:
                print("Please answer yes or no. The conversation has been stopped safely.")
                return

            if attempt == max_attempts:
                print("\\nMaximum of 3 support attempts reached.")
                print("Human review is recommended because the issue remains unresolved.")
                print("No ticket has been sent automatically by this prototype.")
                return

            print("\\nOkay, let's try a different approach. Avoid repeating the same step.")

        except Exception as error:
            print("\\nAn error occurred while processing the ticket.")
            print("Error:", error)
            return


if __name__ == "__main__":
    run_interactive_conversation()
